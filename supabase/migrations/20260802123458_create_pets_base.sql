create table public.pets (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete restrict,
  species_id smallint not null references public.pet_species(id) on delete restrict,

  name text not null,
  breed text,
  is_mixed_breed boolean not null default false,
  sex text not null default 'UNKNOWN',
  birth_date date,
  birth_date_precision text not null default 'UNKNOWN',
  size text not null default 'UNKNOWN',
  weight_kg numeric(6, 2),

  primary_color text,
  secondary_colors text[] not null default '{}',
  description text,
  distinctive_features text,

  has_microchip boolean not null default false,
  microchip_number text,
  identification_notes text,
  private_notes text,

  status text not null default 'ACTIVE',
  visibility text not null default 'PUBLIC_WHEN_REPORTED',

  archived_at timestamptz,
  deceased_at date,

  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),

  constraint pets_name_length
    check (char_length(trim(name)) between 1 and 80),

  constraint pets_breed_length
    check (breed is null or char_length(breed) <= 120),

  constraint pets_sex_valid
    check (sex in ('FEMALE', 'MALE', 'UNKNOWN')),

  constraint pets_birth_date_not_future
    check (birth_date is null or birth_date <= current_date),

  constraint pets_birth_date_precision_valid
    check (birth_date_precision in ('EXACT', 'APPROXIMATE', 'UNKNOWN')),

  constraint pets_birth_date_consistency
    check (
      (birth_date is null and birth_date_precision = 'UNKNOWN')
      or
      (birth_date is not null and birth_date_precision in ('EXACT', 'APPROXIMATE'))
    ),

  constraint pets_size_valid
    check (size in ('TINY', 'SMALL', 'MEDIUM', 'LARGE', 'GIANT', 'UNKNOWN')),

  constraint pets_weight_valid
    check (weight_kg is null or (weight_kg > 0 and weight_kg <= 9999.99)),

  constraint pets_primary_color_length
    check (primary_color is null or char_length(primary_color) <= 80),

  constraint pets_secondary_colors_count
    check (cardinality(secondary_colors) <= 8),

  constraint pets_description_length
    check (description is null or char_length(description) <= 1000),

  constraint pets_distinctive_features_length
    check (
      distinctive_features is null
      or char_length(distinctive_features) <= 1000
    ),

  constraint pets_microchip_format
    check (
      microchip_number is null
      or microchip_number ~ '^[A-Z0-9]{8,30}$'
    ),

  constraint pets_microchip_consistency
    check (
      (has_microchip = false and microchip_number is null)
      or
      (has_microchip = true)
    ),

  constraint pets_identification_notes_length
    check (
      identification_notes is null
      or char_length(identification_notes) <= 1000
    ),

  constraint pets_private_notes_length
    check (private_notes is null or char_length(private_notes) <= 2000),

  constraint pets_status_valid
    check (status in ('ACTIVE', 'ARCHIVED', 'DECEASED')),

  constraint pets_visibility_valid
    check (visibility in ('PRIVATE', 'PUBLIC_WHEN_REPORTED', 'PUBLIC')),

  constraint pets_status_dates_consistency
    check (
      (status = 'ACTIVE' and archived_at is null and deceased_at is null)
      or
      (status = 'ARCHIVED' and archived_at is not null and deceased_at is null)
      or
      (status = 'DECEASED' and archived_at is null and deceased_at is not null)
    )
);

create unique index pets_microchip_unique_idx
  on public.pets (microchip_number)
  where microchip_number is not null;

create index pets_owner_status_updated_idx
  on public.pets (owner_id, status, updated_at desc);

create index pets_species_status_idx
  on public.pets (species_id, status);

create trigger pets_set_updated_at
before update on public.pets
for each row
execute function public.set_updated_at();

-- Evita cambiar el responsable mediante una actualización ordinaria.
create or replace function public.prevent_pet_owner_change()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.owner_id is distinct from old.owner_id then
    raise exception 'PET_OWNER_CHANGE_NOT_ALLOWED'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

create trigger pets_prevent_owner_change
before update of owner_id on public.pets
for each row
execute function public.prevent_pet_owner_change();

