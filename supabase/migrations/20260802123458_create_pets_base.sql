create table public.pet_photos (
  id uuid primary key default gen_random_uuid(),
  pet_id uuid not null references public.pets(id) on delete cascade,
  storage_path text not null,
  position smallint not null default 0,
  is_primary boolean not null default false,
  visibility text not null default 'PRIVATE',
  alt_text text,
  mime_type text,
  file_size_bytes integer,
  width integer,
  height integer,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),

  constraint pet_photos_storage_path_length
    check (char_length(storage_path) between 1 and 500),

  constraint pet_photos_position_valid
    check (position >= 0),

  constraint pet_photos_visibility_valid
    check (visibility in ('PRIVATE', 'PUBLIC_PROFILE', 'PUBLIC_REPORT')),

  constraint pet_photos_alt_text_length
    check (alt_text is null or char_length(alt_text) <= 300),

  constraint pet_photos_mime_type_valid
    check (
      mime_type is null
      or mime_type in ('image/jpeg', 'image/png', 'image/webp')
    ),

  constraint pet_photos_file_size_valid
    check (file_size_bytes is null or file_size_bytes > 0),

  constraint pet_photos_width_valid
    check (width is null or width > 0),

  constraint pet_photos_height_valid
    check (height is null or height > 0)
);

create unique index pet_photos_storage_path_unique_idx
  on public.pet_photos (storage_path);

create unique index pet_photos_one_primary_per_pet_idx
  on public.pet_photos (pet_id)
  where is_primary = true;

create index pet_photos_pet_position_idx
  on public.pet_photos (pet_id, position);

create trigger pet_photos_set_updated_at
before update on public.pet_photos
for each row
execute function public.set_updated_at();

