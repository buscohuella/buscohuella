create table public.pet_species (
  id smallint generated by default as identity primary key,
  code text not null,
  category text not null,
  sort_order smallint not null default 0,
  is_enabled boolean not null default true,
  mvp_enabled boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),

  constraint pet_species_code_format
    check (code ~ '^[A-Z][A-Z0-9_]{1,49}$'),

  constraint pet_species_category_valid
    check (category in ('COMPANION', 'EQUINE', 'FARM', 'OTHER')),

  constraint pet_species_sort_order_valid
    check (sort_order >= 0)
);

create unique index pet_species_code_unique_idx
  on public.pet_species (code);

create index pet_species_catalog_idx
  on public.pet_species (category, is_enabled, mvp_enabled, sort_order);

create trigger pet_species_set_updated_at
before update on public.pet_species
for each row
execute function public.set_updated_at();

