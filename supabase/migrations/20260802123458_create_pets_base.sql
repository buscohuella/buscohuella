alter table public.pet_species enable row level security;
alter table public.pets enable row level security;
alter table public.pet_photos enable row level security;

create policy pet_species_select_enabled
  on public.pet_species
  for select
  to anon, authenticated
  using (is_enabled = true);

create policy pets_select_own
  on public.pets
  for select
  to authenticated
  using ((select auth.uid()) = owner_id);

create policy pets_insert_own
  on public.pets
  for insert
  to authenticated
  with check ((select auth.uid()) = owner_id);

create policy pets_update_own
  on public.pets
  for update
  to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

create policy pet_photos_select_own
  on public.pet_photos
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.pets
      where pets.id = pet_photos.pet_id
        and pets.owner_id = (select auth.uid())
    )
  );

create policy pet_photos_insert_own
  on public.pet_photos
  for insert
  to authenticated
  with check (
    exists (
      select 1
      from public.pets
      where pets.id = pet_photos.pet_id
        and pets.owner_id = (select auth.uid())
    )
  );

create policy pet_photos_update_own
  on public.pet_photos
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.pets
      where pets.id = pet_photos.pet_id
        and pets.owner_id = (select auth.uid())
    )
  )
  with check (
    exists (
      select 1
      from public.pets
      where pets.id = pet_photos.pet_id
        and pets.owner_id = (select auth.uid())
    )
  );

create policy pet_photos_delete_own
  on public.pet_photos
  for delete
  to authenticated
  using (
    exists (
      select 1
      from public.pets
      where pets.id = pet_photos.pet_id
        and pets.owner_id = (select auth.uid())
    )
  );

